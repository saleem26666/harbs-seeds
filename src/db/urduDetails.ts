function fallbackFluentUrdu(herb: Herb): string {
  const name = herb.name_ur || herb.name_en;
  return `${name} ایک قدرتی جڑی بوٹی/بیج ہے جسے لوگ کھانے اور گھریلو استعمال میں لاتے ہیں۔ نیچے آسان زبان میں فوائد، نقصان اور استعمال سمجھیں۔

فوائد:
${herb.benefits_ur}

نقصان اور احتیاط:
${herb.harms_ur}

استعمال کا طریقہ:
${herb.usage_ur}

یاد رکھیں: یہ صرف عام معلومات ہیں، طبی مشورہ نہیں۔ اگر کوئی بیماری ہو یا دوا چل رہی ہو تو استعمال سے پہلے مستند معالج یا حکیم سے ضرور پوچھ لیں۔`;
}

export function getFluentUrduDetail(herb: Herb): string {
  const byEn = FLUENT_URDU[herb.name_en];
  if (byEn) return byEn;

  // Match generated names that contain a curated root, e.g. "Wild Cardamom Seed"
  for (const [key, text] of Object.entries(FLUENT_URDU)) {
    if (herb.name_en.toLowerCase().includes(key.toLowerCase())) {
      return `${herb.name_ur} (${herb.name_en}) کے بارے میں:\n\n${text}`;
    }
  }

  return fallbackFluentUrdu(herb);
}
